function spawnPrompt() {
  // Pick a random type that isn't the same as the last one
  let type;
  do { type = PROMPT_TYPES[Math.floor(Math.random() * PROMPT_TYPES.length)]; }
  while (type === lastPromptType && PROMPT_TYPES.length > 1);
  lastPromptType = type;
  currentPrompt = { type, timer: 0 };
  promptHit = false;
  // Sync next prompt interval to 4 beats of BPM clock
  currentSyncedInterval = Math.min(Math.max(beatInterval * 4, 1.0), 5.0);

  const labels = {
    jump:  '🦘 JUMP!  [SPACE]',
    pose0: '🙌 HANDS UP  [Z]',
    pose1: '😎 LEAN  [X]',
    pose2: '💪 FLEX  [C]',
    pose3: '🪩 DISCO  [V]',
  };
  const colors = {
    jump:  '#44eeff',
    pose0: '#ff88ff',
    pose1: '#44eeff',
    pose2: '#ffcc00',
    pose3: '#00ff88',
  };

  const el   = document.getElementById('beat-prompt');
  const txt  = document.getElementById('beat-prompt-text');
  const bar  = document.getElementById('beat-prompt-bar');
  if (!el) return;
  txt.textContent = labels[type];
  el.style.borderColor = colors[type];
  el.style.color = colors[type];
  bar.style.background = colors[type];
  bar.style.width = '100%';
  el.className = 'show';
}

function updateBeatPrompt(delta) {
  if (!isDancing) return;

  // Tick the between-prompt timer
  if (!currentPrompt) {
    promptTimer += delta;
    if (promptTimer >= currentSyncedInterval) {
      promptTimer = 0;
      spawnPrompt();
    }
    return;
  }

  // Active prompt: tick its window down
  currentPrompt.timer += delta;
  const pct = 1 - (currentPrompt.timer / PROMPT_WINDOW);
  const bar = document.getElementById('beat-prompt-bar');
  if (bar) bar.style.width = Math.max(pct * 100, 0) + '%';

  if (currentPrompt.timer >= PROMPT_WINDOW) {
    if (!promptHit) {
      // Missed
      resetCombo();
      const el = document.getElementById('beat-prompt');
      if (el) { el.className = 'show miss'; setTimeout(() => { if(el) el.className = ''; }, 500); }
    } else {
      const el = document.getElementById('beat-prompt');
      if (el) setTimeout(() => { if(el) el.className = ''; }, 300);
    }
    currentPrompt = null;
    // Start countdown to next prompt immediately after window closes
    promptTimer = currentSyncedInterval * 0.3; // short pause then next one
  }
}

function checkPromptInput(inputType) {
  // Called when player does a jump or pose while a prompt is active
  if (!currentPrompt || promptHit || !isDancing) return;
  if (currentPrompt.type === inputType) {
    promptHit = true;
    // Score based on reaction speed — faster = more points
    const timeLeft = PROMPT_WINDOW - currentPrompt.timer;
    const accuracy = timeLeft / PROMPT_WINDOW; // 0–1
    const pts = Math.round((50 + accuracy * 100) * combo);
    score += pts;
    document.getElementById('score-value').textContent = Math.floor(score);

    // Grow combo
    combo = Math.min(combo + 1, COMBO_MAX);
    document.getElementById('combo-value').textContent = combo;
    document.getElementById('combo-box').classList.toggle('max', combo === COMBO_MAX);

    // Flash
    const fakepose = { bonus: pts, emoji: currentPrompt.type === 'jump' ? '🦘' : POSES[parseInt(currentPrompt.type.slice(4))].emoji, color: '#00ff88' };
    flashPoseBonus(fakepose);

    const el = document.getElementById('beat-prompt');
    if (el) el.className = 'show hit';
  }
}

